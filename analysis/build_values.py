#!/usr/bin/env python3
"""Merge data/values_*.json (producer files only) into data/values.json and
write paper/src/values.tex as LaTeX macros: \\val{<key>} -> formatted value.

Single source of truth: the paper never hard-codes a computed number.
Formatting rules live in analysis/value_formats.json  {key: "fmt"}  (Python format spec),
default = 4 significant figures. Missing keys render in red via \\gap.
"""
import json, glob, os, math, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
OUT_TEX = os.path.join(ROOT, "paper", "src", "values.tex")
EXCLUDE = {"values.json", "values_peec_check.json", "values_V3.json", "values_V4.json", "values_V5.json"}


def flatten(d, prefix=""):
    out = {}
    for k, v in d.items():
        if k.startswith("_"):
            continue
        key = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict) and "value" in v:
            out[key] = v["value"]
        elif isinstance(v, dict):
            out.update(flatten(v, key))
        else:
            out[key] = v
    return out


def fmt(v, spec=None):
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, (int, float)) and not (isinstance(v, float) and math.isnan(v)):
        if spec:
            return format(v, spec)
        if v == 0:
            return "0"
        g = format(v, ".4g")
        if "e" not in g:
            return g
        digits = max(4 - int(math.floor(math.log10(abs(v)))) - 1, 0)
        return f"{v:.{digits}f}"
    return str(v)


def tex_escape(s):
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in [("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"), ("~", r"\textasciitilde{}")]:
        s = s.replace(a, b)
    return s


def main():
    merged, sources = {}, {}
    for path in sorted(glob.glob(os.path.join(DATA, "values_*.json"))):
        name = os.path.basename(path)
        if name in EXCLUDE:
            continue
        with open(path) as fh:
            d = json.load(fh)
        flat = flatten(d)
        for k, v in flat.items():
            if k in merged and merged[k] != v:
                print(f"WARNING: key {k} differs between {sources[k]} and {name}", file=sys.stderr)
            merged[k] = v
            sources[k] = name
    with open(os.path.join(DATA, "values.json"), "w") as fh:
        json.dump({"values": merged, "sources": sources}, fh, indent=1, sort_keys=True)
    fmts = {}
    fpath = os.path.join(ROOT, "analysis", "value_formats.json")
    if os.path.exists(fpath):
        fmts = json.load(open(fpath))
    lines = ["% AUTO-GENERATED by analysis/build_values.py -- do not edit", ""]
    for k in sorted(merged):
        v = merged[k]
        if isinstance(v, (list, dict)):
            continue
        s = fmt(v, fmts.get(k))
        if not isinstance(v, (int, float)):
            s = tex_escape(s)
        elif s.startswith("-"):
            s = r"\ensuremath{-}" + s[1:]   # true minus sign
        elif s.startswith("+") and len(s) > 1:
            s = r"\ensuremath{+}" + s[1:]
        lines.append(r"\expandafter\def\csname val@%s\endcsname{%s}" % (k, s))
    with open(OUT_TEX, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(merged)} values -> data/values.json, paper/src/values.tex")


if __name__ == "__main__":
    main()
